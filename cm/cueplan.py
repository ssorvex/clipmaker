"""Where a sound effect is actually allowed to land.

This is the difference between a clip that sounds produced and one that sounds
like a soundboard fell down the stairs. A model is good at deciding *what*
should go where; it is bad at the mechanical constraints. So the model proposes
cues and this module enforces:

  * snap to a speech gap — never drop a transient on top of a syllable
  * minimum spacing — no machine-gunning
  * density cap scaled to clip length
  * duck the gain when a cue has to sit over speech
  * nothing in the last fraction of a second, where it gets cut off
  * de-duplicate the same effect fired twice in the same breath

Cues that cannot be placed are dropped, with a recorded reason, rather than
being forced in.
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace

from .probe import Probe
from .sfx import RECIPES
from .transcribe import Transcript
from .util import clamp

# Sensible level per role, relative to the normalised asset peak. Transitions
# and beds sit well under the voice; emphasis hits can be a touch louder.
ROLE_GAIN_DB: dict[str, float] = {
    "transition": -15.0,
    "accent": -11.0,
    "emphasis": -13.0,
    "bed": -22.0,
}

# How far a cue may be nudged to find a clean gap.
SNAP_WINDOW = 0.45
# Extra attenuation when a cue lands mid-word with nowhere better to go.
OVER_SPEECH_PENALTY_DB = -4.5

# A build and the hit it lands on are *meant* to be close together, so the
# minimum-spacing rule must not treat the pair as a collision. Without this
# exemption the riser is always dropped in favour of the higher-priority
# impact, leaving a hit with no build — the one thing worse than neither.
BUILD_KINDS = {"riser", "suspense", "heartbeat", "whoosh_reverse", "air"}
LANDING_KINDS = {"impact", "boom", "reveal", "ding", "sparkle", "thud"}


def _is_designed_pair(a: Cue, b: Cue) -> bool:
    """True when a and b are a build followed by its payoff."""
    first, second = (a, b) if a.t <= b.t else (b, a)
    return first.kind in BUILD_KINDS and second.kind in LANDING_KINDS


@dataclass
class Cue:
    """One sound effect at one moment, relative to the start of the clip."""
    t: float                       # seconds from clip start
    kind: str
    gain_db: float
    reason: str = ""
    prompt: str = ""               # text prompt if generated by an API
    variant: int = 0
    priority: float = 1.0          # higher survives thinning
    placed_from: float | None = None
    dropped: str = ""              # non-empty if rejected

    @property
    def role(self) -> str:
        return RECIPES[self.kind].role if self.kind in RECIPES else "accent"

    @property
    def duration(self) -> float:
        return RECIPES[self.kind].duration if self.kind in RECIPES else 0.3

    def to_dict(self) -> dict:
        out = {
            "t": round(self.t, 3),
            "kind": self.kind,
            "gain_db": round(self.gain_db, 2),
            "reason": self.reason,
        }
        if self.placed_from is not None and abs(self.placed_from - self.t) > 0.01:
            out["moved_from"] = round(self.placed_from, 3)
        if self.prompt:
            out["prompt"] = self.prompt
        if self.dropped:
            out["dropped"] = self.dropped
        return out


@dataclass
class PlacementReport:
    kept: list[Cue] = field(default_factory=list)
    dropped: list[Cue] = field(default_factory=list)

    def summary(self) -> str:
        moved = sum(1 for c in self.kept
                    if c.placed_from is not None and abs(c.placed_from - c.t) > 0.02)
        return (f"{len(self.kept)} cues placed"
                f"{f' ({moved} nudged into speech gaps)' if moved else ''}"
                f"{f', {len(self.dropped)} dropped' if self.dropped else ''}")


def default_gain(kind: str) -> float:
    role = RECIPES[kind].role if kind in RECIPES else "accent"
    return ROLE_GAIN_DB.get(role, -12.0)


def _gaps_within(probe: Probe, clip_start: float, clip_end: float) -> list[tuple[float, float]]:
    """Speech gaps expressed relative to the clip, from probe + transcript."""
    out = []
    for start, end in probe.gaps:
        if end <= clip_start or start >= clip_end:
            continue
        out.append((max(0.0, start - clip_start), min(clip_end - clip_start, end - clip_start)))
    return out


def _word_gaps(
    transcript: Transcript, clip_start: float, clip_end: float, *, min_gap: float = 0.12
) -> list[tuple[float, float]]:
    """Gaps between consecutive words — finer grained than the audio envelope."""
    words = transcript.words_between(clip_start, clip_end)
    gaps: list[tuple[float, float]] = []
    if not words:
        return gaps
    rel = [(w.start - clip_start, w.end - clip_start) for w in words]
    rel.sort()
    if rel[0][0] > min_gap:
        gaps.append((0.0, rel[0][0]))
    for (_, prev_end), (next_start, _) in zip(rel, rel[1:]):
        if next_start - prev_end >= min_gap:
            gaps.append((prev_end, next_start))
    tail = clip_end - clip_start
    if tail - rel[-1][1] > min_gap:
        gaps.append((rel[-1][1], tail))
    return gaps


def _word_onsets(
    transcript: Transcript, clip_start: float, clip_end: float
) -> list[float]:
    """Word start times, relative to the clip.

    A transient landing exactly on a word onset is deliberate accenting — it
    reads as emphasis, not as a mistake. Only a cue stranded in the *middle* of
    a word needs to be pulled down.
    """
    return sorted(
        w.start - clip_start
        for w in transcript.words_between(clip_start, clip_end)
        if clip_start <= w.start <= clip_end
    )


def _nearest_gap(t: float, gaps: list[tuple[float, float]], window: float) -> float | None:
    """Pick the point inside the closest gap that is nearest to t."""
    best, best_dist = None, window
    for start, end in gaps:
        if start <= t <= end:
            return t
        target = start if abs(t - start) < abs(t - end) else end
        # Aim a little inside the gap rather than exactly on its edge.
        inset = clamp(target + (0.04 if target == start else -0.04), start, end)
        dist = abs(t - target)
        if dist < best_dist:
            best, best_dist = inset, dist
    return best


def _nearest_onset(t: float, onsets: list[float], window: float) -> float | None:
    best, best_dist = None, window
    for onset in onsets:
        dist = abs(t - onset)
        if dist < best_dist:
            best, best_dist = onset, dist
    return best


def density_cap(clip_duration: float, *, per_seconds: float = 4.0, hard_max: int = 10) -> int:
    """How many cues a clip of this length can carry without sounding busy."""
    return int(clamp(round(clip_duration / per_seconds), 2, hard_max))


def place(
    cues: list[Cue],
    *,
    clip_start: float,
    clip_end: float,
    probe: Probe,
    transcript: Transcript,
    min_spacing: float = 1.1,
    per_seconds: float = 4.0,
    hard_max: int = 10,
    tail_guard: float = 0.30,
) -> PlacementReport:
    """Apply the placement rules. Returns kept and dropped cues."""
    clip_duration = max(0.1, clip_end - clip_start)
    report = PlacementReport()
    if not cues:
        return report

    env_gaps = _gaps_within(probe, clip_start, clip_end)
    wrd_gaps = _word_gaps(transcript, clip_start, clip_end)
    # Word gaps are more precise; fall back to the envelope when there's no ASR.
    gaps = wrd_gaps or env_gaps
    onsets = _word_onsets(transcript, clip_start, clip_end)

    staged: list[Cue] = []
    for cue in cues:
        c = replace(cue, placed_from=cue.t)

        # 1. Inside the clip, clear of the tail.
        if c.t < -0.05 or c.t > clip_duration:
            report.dropped.append(replace(c, dropped="outside clip"))
            continue
        c.t = clamp(c.t, 0.0, max(0.0, clip_duration - tail_guard))

        # 2. Snap to the best nearby landing point. A gap is ideal; a word
        #    onset is a legitimate accent; mid-word is the only bad case.
        snapped = _nearest_gap(c.t, gaps, SNAP_WINDOW) if gaps else None
        if snapped is not None:
            c.t = clamp(snapped, 0.0, max(0.0, clip_duration - tail_guard))
        else:
            onset = _nearest_onset(c.t, onsets, SNAP_WINDOW) if onsets else None
            if onset is not None:
                c.t = clamp(onset, 0.0, max(0.0, clip_duration - tail_guard))
                c.reason = (c.reason + " [on word onset]").strip()
            elif (gaps or onsets) and c.role != "bed":
                # We know where the words are and this cue is stranded inside
                # one, so keep it but pull it down and let the words win.
                c.gain_db += OVER_SPEECH_PENALTY_DB
                c.reason = (c.reason + " [over speech, attenuated]").strip()
            # With no gaps and no onsets we have no idea where the words are,
            # so leave the cue alone rather than attenuating on a guess.

        staged.append(c)

    # 3. Thin by spacing, keeping the highest priority in each cluster.
    staged.sort(key=lambda c: (c.t, -c.priority))
    kept: list[Cue] = []
    for c in staged:
        clash = next((k for k in kept
                      if abs(k.t - c.t) < min_spacing and not _is_designed_pair(k, c)),
                     None)
        if clash is None:
            kept.append(c)
            continue
        if c.priority > clash.priority:
            kept.remove(clash)
            report.dropped.append(replace(clash, dropped=f"too close to {c.kind}"))
            kept.append(c)
        else:
            report.dropped.append(replace(c, dropped=f"too close to {clash.kind}"))

    # 4. Same effect twice in quick succession reads as a glitch.
    deduped: list[Cue] = []
    for c in sorted(kept, key=lambda c: c.t):
        twin = next((d for d in deduped if d.kind == c.kind and abs(d.t - c.t) < 2.5), None)
        if twin is not None:
            if c.priority > twin.priority:
                deduped.remove(twin)
                report.dropped.append(replace(twin, dropped=f"duplicate {c.kind}"))
                deduped.append(c)
            else:
                report.dropped.append(replace(c, dropped=f"duplicate {c.kind}"))
            continue
        deduped.append(c)

    # 5. Density cap — keep the best N.
    cap = density_cap(clip_duration, per_seconds=per_seconds, hard_max=hard_max)
    deduped.sort(key=lambda c: -c.priority)
    survivors = deduped[:cap]
    for c in deduped[cap:]:
        report.dropped.append(replace(c, dropped="density cap"))

    # 6. Give repeated kinds different variants so they don't sound identical.
    seen: dict[str, int] = {}
    for c in sorted(survivors, key=lambda c: c.t):
        n = seen.get(c.kind, 0)
        c.variant = n
        seen[c.kind] = n + 1

    report.kept = sorted(survivors, key=lambda c: c.t)
    return report


def default_cues(
    clip_duration: float,
    *,
    has_scene_cut_at_end: bool = False,
    first_word_at: float | None = None,
    sentence_breaks: list[float] | None = None,
) -> list[Cue]:
    """The structural bed every clip gets, before any model input.

    A build into the first line and a hit when it lands is the single most
    reliable pattern in short-form, and it works with no transcript at all.

    When word timings *are* available, the build is aimed at the first word
    rather than at a fixed offset: the riser resolves exactly as the speaker
    starts, which is the whole point of a build. A fixed 0.05s/1.15s pair
    lands wherever it happens to land, which is usually mid-syllable.
    """
    riser = RECIPES["riser"].duration
    if first_word_at is not None and first_word_at > 0.15:
        land = min(first_word_at, max(0.0, clip_duration - 1.0))
    else:
        land = min(1.20, max(0.0, clip_duration * 0.1))
    build_start = max(0.0, land - riser * 0.92)

    cues = [
        Cue(t=land, kind="impact", gain_db=default_gain("impact"),
            reason="hook lands", priority=2.2),
    ]
    # Only add the build if there is room for most of it. A riser squeezed into
    # a third of its length doesn't read as a build, it reads as a glitch — and
    # its payoff would arrive before it finished.
    if land - build_start >= riser * 0.55:
        cues.insert(0, Cue(t=build_start, kind="riser",
                           gain_db=default_gain("riser"),
                           reason="build into the hook", priority=2.0))

    # Mid-clip beat change: prefer a real sentence break near the middle over
    # an arbitrary percentage of the duration, but don't drift to the edges
    # chasing one — a "mid-clip" accent at 80% is just a late accent.
    if clip_duration > 14:
        target = clip_duration * 0.55
        if sentence_breaks:
            nearby = [b for b in sentence_breaks
                      if 0.30 * clip_duration < b < 0.70 * clip_duration]
            if nearby:
                target = min(nearby, key=lambda b: abs(b - target))
        cues.append(Cue(t=target, kind="whoosh", gain_db=default_gain("whoosh"),
                        reason="mid-clip beat change", priority=0.9))

    if has_scene_cut_at_end and clip_duration > 8:
        cues.append(Cue(t=max(0.0, clip_duration - 1.2), kind="swish",
                        gain_db=default_gain("swish"),
                        reason="outgoing cut", priority=0.7))
    return cues


def structural_context(
    transcript: Transcript, clip_start: float, clip_end: float
) -> tuple[float | None, list[float]]:
    """First word onset and sentence-ending times, relative to the clip."""
    words = transcript.words_between(clip_start, clip_end)
    if not words:
        return None, []
    first = min(w.start for w in words) - clip_start
    breaks = [
        w.end - clip_start for w in words
        if w.text.rstrip().endswith((".", "!", "?"))
    ]
    return max(0.0, first), sorted(b for b in breaks if 0 < b < clip_end - clip_start)
